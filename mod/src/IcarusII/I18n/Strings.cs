        private static readonly Dictionary<string, Dictionary<string, string>> Tables =
            new Dictionary<string, Dictionary<string, string>>
            {
                ["zh-CN"] = ZhCn,
            };

        public static string Get(string key, params object[] args)
        {
            var table = ResolveTable();
            if (!table.TryGetValue(key, out var value))
            {
                // 回退到中文，再回退到 key 本身（便于暴露缺失项）
                if (!ZhCn.TryGetValue(key, out value)) value = key;
            }
            return args is not null && args.Length > 0 ? string.Format(value, args) : value;
        }

        /// <summary>与 Get 相同，但数字按 InvariantCulture 格式化（日志/卡片等固定格式）。</summary>
        public static string GetInvariant(string key, params object[] args)
        {
            var table = ResolveTable();
            if (!table.TryGetValue(key, out var value))
            {
                if (!ZhCn.TryGetValue(key, out value)) value = key;
            }
            return args is not null && args.Length > 0
                ? string.Format(CultureInfo.InvariantCulture, value, args)
                : value;
        }

        private static Dictionary<string, string> ResolveTable()
        {
            var code = GameRefs.LanguageCode;
            if (!string.IsNullOrEmpty(code) && Tables.TryGetValue(code, out var table))
                return table;
            return ZhCn;
        }
