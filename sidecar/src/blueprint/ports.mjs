/** 按建筑 yaw 旋转本地偏移（yaw 0/90/180/270）。 */
export function rotateOffset(dx, dy, yaw) {
  const deg = ((Math.round(yaw ?? 0) % 360) + 360) % 360;
  if (deg === 90) return { dx: dy, dy: -dx };
  if (deg === 180) return { dx: -dx, dy: -dy };
  if (deg === 270) return { dx: -dy, dy: dx };
  return { dx, dy };
}
